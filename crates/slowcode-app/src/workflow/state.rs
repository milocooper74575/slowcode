//! Structured Plan workflow state and phase gates.
//!
//! The state is the source of truth. Markdown artifacts are views and never
//! decide whether a command may run. Gates live here so every caller shares the
//! same rule set.

use std::{fmt, path::Path};

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use thiserror::Error;

/// Schema version written into `state.json`.
pub const SCHEMA_VERSION: u32 = 1;

/// Lifecycle status. Phase is separate.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum WorkflowStatus {
    Active,
    Paused,
    Completed,
    Blocked,
    Ended,
}

impl WorkflowStatus {
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Active => "active",
            Self::Paused => "paused",
            Self::Completed => "completed",
            Self::Blocked => "blocked",
            Self::Ended => "ended",
        }
    }

    #[must_use]
    pub fn is_terminal(self) -> bool {
        matches!(self, Self::Completed | Self::Ended)
    }
}

impl fmt::Display for WorkflowStatus {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

/// Effective read/write capability for one phase.
///
/// Profiles are not user-visible roles. `Navigator` and `Driver` map to the
/// two installed roles; `Coach` and `Auditor` are read-only navigator variants.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CapabilityProfile {
    Navigator,
    Driver,
    Coach,
    Auditor,
}

impl CapabilityProfile {
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Navigator => "navigator",
            Self::Driver => "driver",
            Self::Coach => "coach",
            Self::Auditor => "auditor",
        }
    }

    /// User-visible role backing this profile.
    #[must_use]
    pub fn role_name(self) -> &'static str {
        match self {
            Self::Driver => "driver",
            Self::Navigator | Self::Coach | Self::Auditor => "navigator",
        }
    }

    #[must_use]
    pub fn is_read_only(self) -> bool {
        !matches!(self, Self::Driver)
    }
}

/// One phase of the Plan workflow.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Phase {
    Classify,
    Interview,
    Reclassify,
    Review,
    Scaffold,
    AwaitUser,
    TestFix,
    Distill,
    Done,
    Blocked,
}

impl Phase {
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Classify => "classify",
            Self::Interview => "interview",
            Self::Reclassify => "reclassify",
            Self::Review => "review",
            Self::Scaffold => "scaffold",
            Self::AwaitUser => "await_user",
            Self::TestFix => "test_fix",
            Self::Distill => "distill",
            Self::Done => "done",
            Self::Blocked => "blocked",
        }
    }

    /// Only the phases that own workspace changes may write user files.
    #[must_use]
    pub fn allows_workspace_write(self) -> bool {
        matches!(self, Self::Scaffold | Self::TestFix)
    }

    /// Effective capability profile, or `None` when the phase has no role.
    #[must_use]
    pub fn capability_profile(self) -> Option<CapabilityProfile> {
        match self {
            Self::Classify | Self::Interview | Self::Reclassify | Self::Review => {
                Some(CapabilityProfile::Navigator)
            }
            Self::Scaffold | Self::TestFix => Some(CapabilityProfile::Driver),
            Self::AwaitUser => Some(CapabilityProfile::Coach),
            Self::Distill => Some(CapabilityProfile::Auditor),
            Self::Done | Self::Blocked => None,
        }
    }
}

impl fmt::Display for Phase {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

